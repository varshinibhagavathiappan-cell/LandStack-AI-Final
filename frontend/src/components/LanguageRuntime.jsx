const reverse = {};
for (const lang of Object.keys(PAIRS)) {
  for (const [key, value] of Object.entries(PAIRS[lang])) reverse[value] = key;
}

export default function LanguageRuntime({ language }) {
  useEffect(() => {
    const target = PAIRS[language] || PAIRS.en;
    const root = document.getElementById('root');
    if (!root) return;
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const nodes = [];
    let node;
    while ((node = walker.nextNode())) nodes.push(node);
    for (const textNode of nodes) {
      const parent = textNode.parentElement;
      if (!parent || /^(INPUT|TEXTAREA|SCRIPT|STYLE|OPTION)$/.test(parent.tagName) || parent.isContentEditable) continue;
      const raw = textNode.nodeValue || '';
      const trimmed = raw.trim();
      if (!trimmed || trimmed.length > 100) continue;
      const canonical = reverse[trimmed];
      if (!canonical) continue;
      const translated = target[canonical];
      if (translated && translated !== trimmed) textNode.nodeValue = raw.replace(trimmed, translated);
    }
  }, [language]);
  return null;
}
